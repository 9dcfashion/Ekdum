// Bundles supabase/migrations/*.sql into one file that can be pasted into the
// Supabase SQL Editor: supabase/ekdum_schema.sql
// Usage: pnpm db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase", "migrations");
const all = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
// The scheduler needs pg_cron, pg_net and Vault secrets that only make sense once
// the app is deployed, so it ships as a separate, optional script.
const files = all.filter((f) => !/scheduler/.test(f));
const schedulerFiles = all.filter((f) => /scheduler/.test(f));

const header = `-- ════════════════════════════════════════════════════════════════════════════
-- EkDum · full database schema (Phase 1)
-- Generated by "pnpm db:bundle" from supabase/migrations. Do not edit by hand.
--
-- HOW TO USE
--   1. Create a Supabase project in the Mumbai (ap-south-1) region.
--   2. Open SQL Editor → New query, paste this whole file, and click Run.
--   3. Run it ONCE on a fresh project. It is not written to be re-run.
--
-- Files included, in order:
${files.map((f) => `--   ${f}`).join("\n")}
-- ════════════════════════════════════════════════════════════════════════════

begin;
`;

const body = files
  .map((f) => `\n-- ▶ ${f}\n\n${readFileSync(path.join(dir, f), "utf8").trim()}\n`)
  .join("\n");

const out = path.join(root, "supabase", "ekdum_schema.sql");
writeFileSync(out, `${header}${body}\ncommit;\n`);
console.log(`Wrote ${path.relative(root, out)} (${files.length} migrations)`);

const schedulerOut = path.join(root, "supabase", "ekdum_scheduler.sql");
writeFileSync(
  schedulerOut,
  `-- EkDum · optional scheduler (run AFTER ekdum_schema.sql and after the app is deployed).
-- Generated by "pnpm db:bundle". See docs/RUNBOOK.md, "Receipt retries".

${schedulerFiles.map((f) => readFileSync(path.join(dir, f), "utf8").trim()).join("\n\n")}
`,
);
console.log(`Wrote ${path.relative(root, schedulerOut)}`);
